/**
 * The relationship manager's book: forty-six customers behind the four heroes.
 *
 * Synthetic, like everything in this package, and labelled so wherever the console shows them.
 * What makes a book look like a book rather than forty-six copies of one customer is that the
 * differences are the ones an RM actually sorts by: age and life stage, how the money arrives
 * (a salary, a shop's takings, a practice's fees), how much of it is left at the end of the
 * month, where else it is kept, and the one thing about each customer that would make an RM
 * pick up the phone. Each entry's `demonstrates` names that thing, and the tests in
 * `book.test.ts` hold the book to the spread the console needs: every insight the engine can
 * raise, all three segments, multi-bank customers, and a healthy majority who are simply fine.
 *
 * Every figure is behaviour, not a balance: an income, a rent, a budget, a loan's remaining
 * tenure. The balances, the surplus, the signals and the segment all fall out of the ledger the
 * generator writes from them, exactly as they do for the heroes.
 */
